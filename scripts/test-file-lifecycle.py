def changed(doc, path, value):
    result = copy.deepcopy(doc)
    target = result
    for key in path[:-1]:
        target = target[key]
    target[path[-1]] = value
    return result


def prefix(doc, count, through=None):
    result = copy.deepcopy(doc)
    result["events"] = result["events"][:count]
    return seal(result, through)


def audit(doc):
    return verify_document(decode_json(json.dumps(doc, ensure_ascii=True, allow_nan=False)))


class LifecycleOracles(unittest.TestCase):
    def bad(self, doc):
        with self.assertRaises(Invalid):
            verify_document(doc)

    def test_publication_copy_and_late_visibility(self):
        report = audit(publication())
        self.assertEqual("VALID_COMPLETE", report["status"])
        self.assertTrue(report["completeCaptureCertified"])
        self.assertFalse(report["fluidServiceAccountingCertified"])
        self.assertFalse(report["contextualRunChecked"])
        self.assertEqual((1, 1, 0, 0), tuple(report[key] for key in
                                          ("admissionCount", "settlementCount", "activeCopyCount", "waitingJobCount")))
        self.assertEqual(300, report["facts"]["jobs"][1]["requiredReferenceBytes"])
        self.assertEqual(15, report["facts"]["jobs"][1]["dataReadyAt"])
        target = report["facts"]["replicas"][1]
        self.assertEqual((15, 1, 1), (target["visibleAt"], target["origin"]["observedAt"], target["copyOrdinal"]))
        self.assertEqual(loc(1), target["copiedFrom"])
        self.assertTrue(report["lifecycleQuiescent"])

    def test_both_models_and_empty_are_complete_not_disabled(self):
        for isolated in (False, True):
            doc = document(isolated=isolated)
            result = audit(doc)
            self.assertEqual("VALID_COMPLETE", result["status"])
            self.assertEqual(0, result["admissionCount"])
        doc = publication()
        doc["modelKind"] = "COHERENT_FILE_DATAFLOW_NO_CONTENTION_V2"
        doc["policies"]["sharing"] = "ISOLATED_PATH_BOTTLENECK"
        self.assertEqual(1, audit(doc)["settlementCount"])

    def test_complete_operation_prefix_can_wait_run_or_be_ready(self):
        waiting = audit(prefix(publication(), 7, 2))
        self.assertEqual((1, 1, 1), (waiting["activeCopyCount"], waiting["waitingJobCount"], waiting["unfinishedJobCount"]))
        self.assertFalse(waiting["lifecycleQuiescent"])
        ready_report = audit(prefix(publication(), 9))
        self.assertEqual(1, ready_report["readyNotStartedJobCount"])
        running = audit(prefix(publication(), 10))
        self.assertEqual(1, running["runningJobCount"])
        # The standalone scope cannot authenticate deletion of a whole valid
        # suffix or join this prefix to an enclosing completed-run manifest.
        self.assertEqual("VALID_COMPLETE", waiting["status"])

    def test_fanin_independent_publication_join_and_cache_origin(self):
        full = fanin()
        early = audit(prefix(full, 13))
        self.assertEqual(1, early["waitingJobCount"])
        self.assertEqual(1, early["activeCopyCount"])
        self.assertEqual(1, early["readyNotStartedJobCount"])
        report = audit(full)
        copy3 = report["facts"]["copies"][2]
        self.assertEqual(["VM:2", "VM:3"], copy3["resources"])
        self.assertEqual(loc(2), copy3["sourceReplica"]["location"])
        self.assertEqual(loc(1), copy3["sourceReplica"]["origin"]["location"])
        self.assertEqual((4, 1), (copy3["sourceReplica"]["visibleAt"], copy3["sourceReplica"]["copyOrdinal"]))
        self.assertEqual(3, report["admissionCount"])
        self.assertEqual("JOIN_EXISTING", report["facts"]["jobs"][2]["inputs"][0]["resolution"])

