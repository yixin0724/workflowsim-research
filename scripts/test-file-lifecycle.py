def fat_fabric(k=2, cores=1, placements=((10, 0, 0), (20, 1, 0))):
    """Declare physical inventory; the expected paths below are independent literals."""
    fabric = endpoints(((1, 50), (2, 40), (3, 30)))
    fabric["vmHostAssignments"] = [dict(vmId=1, hostId=10), dict(vmId=2, hostId=20), dict(vmId=3, hostId=10)]
    fabric["topology"] = dict(kind="FAT_TREE", k=k, coreSwitchCount=cores, linkBandwidthBytesPerSecond=10,
                              hostPlacements=[dict(hostId=h, pod=p, edge=e) for h, p, e in placements])
    half = k // 2
    pairs = [("ACC:" + str(h), f"EDGE:{p}:{e}") for h, p, e in placements]
    pairs += [(f"EDGE:{p}:{e}", f"AGG:{p}:{a}") for p in range(k) for e in range(half) for a in range(half)]
    pairs += [(f"AGG:{p}:{c // half}", "CORE:" + str(c)) for p in range(k) for c in range(cores)]
    for a, b in pairs:
        fabric["resources"].extend([dict(key=f"LINK:{a}->{b}", capacityBytesPerSecond=10),
                                    dict(key=f"LINK:{b}->{a}", capacityBytesPerSecond=10)])
    return fabric


