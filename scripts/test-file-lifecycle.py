    def test_failure_retry_preserves_cache_and_only_success_publishes(self):
        doc = failure_retry()
        failed = audit(prefix(doc, 13))
        self.assertFalse(any(r["fileId"] == fid("out") for r in failed["facts"]["replicas"]))
        report = audit(doc)
        jobs = {j["jobId"]: j for j in report["facts"]["jobs"]}
        self.assertFalse(jobs[10]["success"])
        self.assertEqual("LOCAL", jobs[11]["inputs"][0]["resolution"])
        self.assertEqual(2, report["admissionCount"])
        out = next(r for r in report["facts"]["replicas"] if r["fileId"] == fid("out"))
        self.assertEqual((11, 15), (out["origin"]["jobAttemptId"], out["origin"]["observedAt"]))
        wrong = changed(doc, ("events", 19, "payload", "sourceReplica", "origin", "jobAttemptId"), 10)
        self.bad(wrong)
        too_early = prefix(doc, 13)
        too_early["events"].append(request(12, 1, 2, 13))
        self.bad(seal(too_early))

