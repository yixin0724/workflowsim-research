def fid(name="data", scope=0):
    return dict(workflowInputIndex=scope, name=name)


def loc(vm=None):
    return dict(kind="SOURCE" if vm is None else "VM", vmId=vm,
                sourceId="source" if vm is None else None)


def file(name, size, producer=None, scope=0):
    return dict(fileId=fid(name, scope), bytes=size, producerTaskId=producer)


def task(ident, parents=(), inputs=(), outputs=(), scope=0):
    return dict(taskId=ident, workflowInputIndex=scope, parents=list(parents),
                inputs=[dict(fileId=fid(name, scope), referenceCount=count) for name, count in inputs],
                outputs=[fid(name, scope) for name in outputs])


def endpoints(vms=((1, 10), (2, 20), (3, 50))):
    return dict(locations=[loc(vm) for vm, _ in vms] + [loc()],
                resources=[dict(key="VM:" + str(vm), capacityBytesPerSecond=rate) for vm, rate in vms],
                vmHostAssignments=[], topology=None)


def e(kind, now, **payload):
    return dict(sequence=0, type=kind, observedTime=now, payload=payload)


def request(job, tid, vm, now):
    return e("JOB_INPUT_REQUESTED", now, jobId=job, taskIds=[tid], destinationVmId=vm)


def ready(job, now):
    return e("JOB_DATA_READY", now, jobId=job)


def cpu(job, vm, now):
    return e("JOB_CPU_STARTED", now, jobId=job, vmId=vm)


def finish(job, tid, vm, now, success=True):
    return e("TASK_FINISHED", now, jobId=job, taskId=tid, vmId=vm, success=success)


def seed(name, scope=0):
    return e("EXTERNAL_SEEDED", 0, fileId=fid(name, scope), location=loc())


def replica(name, holder, visible, acquisition, producer=None, attempt=None,
            origin_holder=None, origin_at=0, copied_from=None, ordinal=None, scope=0):
    return dict(fileId=fid(name, scope), location=loc(holder), visibleAt=visible, acquisition=acquisition,
                origin=dict(producerTaskId=producer, jobAttemptId=attempt,
                            location=loc(origin_holder), observedAt=origin_at),
                copiedFrom=copied_from, copyOrdinal=ordinal)


def admit(ordinal, name, source, vm, size, path, rate, seconds, now, scope=0):
    return e("COPY_ADMITTED", now, copyOrdinal=ordinal, fileId=fid(name, scope), bytes=size,
             sourceReplica=source, destinationVmId=vm, resources=path,
             standaloneRate=rate, isolatedSeconds=seconds)


def resolve(job, name, resolution, source, now, ordinal=None, count=1, scope=0):
    return e("INPUT_RESOLVED", now, jobId=job, fileId=fid(name, scope), referenceCount=count,
             resolution=resolution, copyOrdinal=ordinal, source=loc(source))


def settle(ordinal, effective, observed, residual=0):
    return e("COPY_SETTLED", observed, copyOrdinal=ordinal,
             effectiveTime=effective, remainingAfterService=residual)


def seal(doc, through=None):
    """Re-sequence and recount after mutation: bookkeeping cannot hide a semantic deletion."""
    for sequence, event in enumerate(doc["events"], 1):
        event["sequence"] = sequence
    doc["capture"]["retainedRecords"] = len(doc["events"])
    doc["capture"]["observedThrough"] = (doc["events"][-1]["observedTime"] if doc["events"] else 0) if through is None else through
    return doc


def document(tasks=(), files=(), events=(), fabric=None, isolated=False):
    doc = dict(schema="workflowsim-file-lifecycle-v2",
               modelKind="COHERENT_FILE_DATAFLOW_NO_CONTENTION_V2" if isolated else "COHERENT_FILE_DATAFLOW_V2",
               recording=dict(mode="FILE_LIFECYCLE_V2", maxTraceRecords=1000),
               certificateScope="FILE_LIFECYCLE_NOT_FLUID_SERVICE_ACCOUNTING_V2",
               policies=dict(fileIdentity="SCOPED_RESOLVED_WRITE_ONCE_FILES_V2",
                             release="DEPENDENCY_READY_AT_OBSERVATION_V2",
                             visibility="PER_FILE_SETTLEMENT_OBSERVATION_V2",
                             selection="VISIBLE_LOCAL_OR_MAX_ISOLATED_RATE_STABLE_LOCATION_V2",
                             sourceAccess="UNBOUNDED_OFF_FABRIC_SOURCE_INPUT_V2",
                             sharing="ISOLATED_PATH_BOTTLENECK" if isolated else "SHARED_MAX_MIN"),
               capture=dict(status="COMPLETE", observedThrough=0, retainedRecords=0, droppedRecords=0),
               filePlan=dict(contractVersion="SCOPED_RESOLVED_WRITE_ONCE_FILES_V2", tasks=list(tasks), files=list(files)),
               fabric=endpoints() if fabric is None else fabric, events=list(events))
    return seal(doc)


